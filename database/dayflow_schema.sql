-- Task Flow Oracle schema for an empty application schema.
-- This script creates tables and must not be used as a reset script.
CREATE TABLE USERS (
  USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  FULL_NAME VARCHAR2(120) NOT NULL,
  USERNAME VARCHAR2(30) NOT NULL,
  EMAIL VARCHAR2(180) NOT NULL UNIQUE,
  PASSWORD_HASH VARCHAR2(500) NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT UQ_USERS_USERNAME UNIQUE(USERNAME)
);
CREATE UNIQUE INDEX UQ_USERS_USERNAME_CI ON USERS (LOWER(USERNAME));
CREATE UNIQUE INDEX UQ_USERS_EMAIL_CI ON USERS (LOWER(EMAIL));

CREATE TABLE CATEGORIES (
  CATEGORY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USER_ID NUMBER NOT NULL REFERENCES USERS(USER_ID) ON DELETE CASCADE,
  CATEGORY_NAME VARCHAR2(80) NOT NULL,
  CONSTRAINT UQ_CATEGORY_USER_NAME UNIQUE(USER_ID, CATEGORY_NAME)
);

CREATE TABLE TASKS (
  TASK_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USER_ID NUMBER NOT NULL REFERENCES USERS(USER_ID) ON DELETE CASCADE,
  CATEGORY_ID NUMBER REFERENCES CATEGORIES(CATEGORY_ID) ON DELETE SET NULL,
  TITLE VARCHAR2(180) NOT NULL,
  DESCRIPTION VARCHAR2(2000),
  PRIORITY VARCHAR2(10) DEFAULT 'MEDIUM' NOT NULL,
  STATUS VARCHAR2(15) DEFAULT 'PENDING' NOT NULL,
  DUE_DATE DATE,
  DUE_TIME VARCHAR2(5),
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  COMPLETED_AT TIMESTAMP,
  REPEAT_TYPE VARCHAR2(10) DEFAULT 'NONE' NOT NULL,
  CONSTRAINT CK_TASK_PRIORITY CHECK(PRIORITY IN ('HIGH','MEDIUM','LOW')),
  CONSTRAINT CK_TASK_STATUS CHECK(STATUS IN ('PENDING','COMPLETED')),
  CONSTRAINT CK_TASK_REPEAT CHECK(REPEAT_TYPE IN ('NONE','DAILY','WEEKLY','MONTHLY'))
);

CREATE TABLE SUBTASKS (
  SUBTASK_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  TASK_ID NUMBER NOT NULL REFERENCES TASKS(TASK_ID) ON DELETE CASCADE,
  TITLE VARCHAR2(300) NOT NULL,
  STATUS VARCHAR2(15) DEFAULT 'PENDING' NOT NULL,
  CONSTRAINT CK_SUBTASK_STATUS CHECK(STATUS IN ('PENDING','COMPLETED'))
);

CREATE TABLE REMINDERS (
  REMINDER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  TASK_ID NUMBER NOT NULL REFERENCES TASKS(TASK_ID) ON DELETE CASCADE,
  REMINDER_TIME TIMESTAMP NOT NULL,
  STATUS VARCHAR2(15) DEFAULT 'PENDING' NOT NULL
);

CREATE TABLE ACHIEVEMENTS (
  ACHIEVEMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NAME VARCHAR2(80) NOT NULL UNIQUE,
  DESCRIPTION VARCHAR2(250) NOT NULL,
  REQUIRED_VALUE NUMBER NOT NULL
);

CREATE TABLE USER_ACHIEVEMENTS (
  USER_ID NUMBER NOT NULL REFERENCES USERS(USER_ID) ON DELETE CASCADE,
  ACHIEVEMENT_ID NUMBER NOT NULL REFERENCES ACHIEVEMENTS(ACHIEVEMENT_ID) ON DELETE CASCADE,
  UNLOCKED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_USER_ACH PRIMARY KEY(USER_ID, ACHIEVEMENT_ID)
);

CREATE TABLE PRODUCTIVITY (
  PRODUCTIVITY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USER_ID NUMBER NOT NULL REFERENCES USERS(USER_ID) ON DELETE CASCADE,
  WORK_DATE DATE NOT NULL,
  COMPLETED_TASKS NUMBER DEFAULT 0 NOT NULL,
  FOCUS_MINUTES NUMBER DEFAULT 0 NOT NULL,
  CONSTRAINT UQ_PRODUCTIVITY_USER_DATE UNIQUE(USER_ID, WORK_DATE)
);

CREATE INDEX IDX_TASK_USER_DATE ON TASKS(USER_ID, DUE_DATE);
CREATE INDEX IDX_TASK_USER_STATUS ON TASKS(USER_ID, STATUS);
CREATE INDEX IDX_SUBTASK_TASK ON SUBTASKS(TASK_ID);

