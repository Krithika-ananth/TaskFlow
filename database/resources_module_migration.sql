-- Task Flow Resources module migration.
-- The supplied project schema contains no Resources table. This migration creates only that table.
-- Do not drop or recreate existing tables.

DECLARE
  table_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO table_count FROM USER_TABLES WHERE TABLE_NAME='RESOURCES';
  IF table_count = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE RESOURCES (
        RESOURCE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        USER_ID NUMBER NOT NULL REFERENCES USERS(USER_ID) ON DELETE CASCADE,
        RESOURCE_TYPE VARCHAR2(10) NOT NULL,
        TITLE VARCHAR2(180) NOT NULL,
        DESCRIPTION VARCHAR2(2000),
        ORIGINAL_FILENAME VARCHAR2(255),
        CONTENT_TYPE VARCHAR2(180),
        FILE_SIZE NUMBER DEFAULT 0 NOT NULL,
        STORAGE_PATH VARCHAR2(1000),
        RESOURCE_URL VARCHAR2(2000),
        CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
        UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
        CONSTRAINT CK_RESOURCES_TYPE CHECK (RESOURCE_TYPE IN ('DOCUMENT','LINK')),
        CONSTRAINT CK_RESOURCES_DOCUMENT_DATA CHECK (
          (RESOURCE_TYPE='DOCUMENT' AND ORIGINAL_FILENAME IS NOT NULL AND STORAGE_PATH IS NOT NULL AND RESOURCE_URL IS NULL)
          OR
          (RESOURCE_TYPE='LINK' AND RESOURCE_URL IS NOT NULL AND ORIGINAL_FILENAME IS NULL AND STORAGE_PATH IS NULL)
        )
      )
    ]';
    EXECUTE IMMEDIATE 'CREATE INDEX IDX_RESOURCES_USER_TYPE ON RESOURCES(USER_ID, RESOURCE_TYPE, CREATED_AT)';
  END IF;
END;
/
COMMIT;
