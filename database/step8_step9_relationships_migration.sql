-- Additive migration for persistent friend relationships and task participants.
-- Apply once to an existing Task Flow schema. Does not modify existing tables.
CREATE TABLE FRIEND_REQUESTS (
  REQUEST_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  SENDER_USER_ID NUMBER NOT NULL REFERENCES USERS(USER_ID) ON DELETE CASCADE,
  RECEIVER_USER_ID NUMBER NOT NULL REFERENCES USERS(USER_ID) ON DELETE CASCADE,
  STATUS VARCHAR2(12) DEFAULT 'PENDING' NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  RESPONDED_AT TIMESTAMP,
  CONSTRAINT CK_FRIEND_REQUEST_STATUS CHECK (STATUS IN ('PENDING','ACCEPTED','REJECTED')),
  CONSTRAINT CK_FRIEND_REQUEST_NOT_SELF CHECK (SENDER_USER_ID <> RECEIVER_USER_ID)
);

-- One active row per unordered pair prevents duplicate/crossed pending requests
-- and duplicate friendships while allowing a new request after rejection/removal.
CREATE UNIQUE INDEX UQ_FRIEND_ACTIVE_PAIR ON FRIEND_REQUESTS (
  CASE WHEN STATUS IN ('PENDING','ACCEPTED') THEN LEAST(SENDER_USER_ID, RECEIVER_USER_ID) END,
  CASE WHEN STATUS IN ('PENDING','ACCEPTED') THEN GREATEST(SENDER_USER_ID, RECEIVER_USER_ID) END
);
CREATE INDEX IDX_FRIEND_RECEIVER_STATUS ON FRIEND_REQUESTS(RECEIVER_USER_ID, STATUS, CREATED_AT);
CREATE INDEX IDX_FRIEND_SENDER_STATUS ON FRIEND_REQUESTS(SENDER_USER_ID, STATUS, CREATED_AT);

CREATE TABLE TASK_SHARES (
  SHARE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  TASK_ID NUMBER NOT NULL REFERENCES TASKS(TASK_ID) ON DELETE CASCADE,
  USER_ID NUMBER NOT NULL REFERENCES USERS(USER_ID) ON DELETE CASCADE,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT UQ_TASK_SHARE_USER UNIQUE(TASK_ID, USER_ID)
);
CREATE INDEX IDX_TASK_SHARES_USER ON TASK_SHARES(USER_ID, TASK_ID);
COMMIT;
